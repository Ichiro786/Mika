/**
 * The licenses page (from "Apache-2.0 open-source license" at the bottom of About): the license text
 * (assets/licenses/Apache-2.0.txt), then Mika as upstream and every third-party component, one row each (name,
 * license) with its note below; the footer points to the full texts.
 */
@Composable
fun LicensesScreen(onBack: () -> Unit) {
    BackHandler(onBack = onBack)
    val context = LocalContext.current
    val licenseText = remember {
        runCatching { context.assets.open(LICENSE_ASSET).use { it.readBytes().decodeToString() } }.getOrDefault("")
    }
    val runtime = remember {
        runCatching { context.assets.open("runtime/packages.json").use { Licenses.runtimePackages(it.readBytes().decodeToString()) } }
            .getOrDefault(emptyList())
    }
    val thirdParty = Licenses.ENTRIES.filter { it.name != Licenses.SELF } + runtime
    SubPage(AboutCopy.LICENSE_TITLE, onBack) {
        if (licenseText.isNotEmpty()) {
            MikaCard(Modifier.padding(bottom = MikaSpace.S12).testTag("license-text")) {
                Text(
                    licenseText.trimEnd(), Modifier.padding(MikaSpace.S16),
                    style = MikaType.Micro.copy(fontWeight = androidx.compose.ui.text.font.FontWeight.Normal, fontFamily = FontFamily.Monospace, lineHeight = MikaType.Hint.lineHeight),
                    color = MikaTheme.colors.ink2,
                )
            }
        }
        GroupLabel(stringResource(R.string.licenses_third_party, thirdParty.size))
        GroupCard {
            thirdParty.forEachIndexed { i, e ->
                Column {
                    ListRow(null, e.name, e.license, first = i == 0)
                    Text(e.note, Modifier.padding(start = MikaSpace.S16, end = MikaSpace.S16, bottom = MikaSpace.S12), style = MikaType.Hint, color = MikaTheme.colors.ink2)
                }
            }
        }
        FooterNote(stringResource(R.string.licenses_footer))
    }
}

private const val LICENSE_ASSET = "licenses/Apache-2.0.txt"
